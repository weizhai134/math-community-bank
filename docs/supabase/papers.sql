# 社区试卷：表与 Storage 策略

前端上传流程：

1. `storage.from('papers').upload('<userId>/<timestamp>-<random>.<ext>', file)`
2. `storage.from('papers').getPublicUrl(path)`
3. `community_papers.insert({ title, description, file_url, file_name, file_type, file_size, nickname, author_id, ... })`

前端兼容了 `file_url / url / file_path`、`file_name / filename`、`author_id / uploader_id` 等常见列名；第一次插入遇到“列不存在”会自动剔除该列重试。但**表里至少要有一个公开可访问的文件 URL 列（推荐 `file_url`）、标题列和上传者列**。

## 1. 先核对实际列名

在 Supabase SQL Editor 执行：

```sql
select column_name, data_type, is_nullable, column_default
from information_schema.columns
where table_schema = 'public' and table_name = 'community_papers'
order by ordinal_position;
```

如果表已经有自己的列名，下面 SQL 里的 `author_id` / `file_url` 换成实际列名即可；前端也能读 `uploader_id` / `url` 等别名。

## 2. 推荐表结构

如果还没建表，或想补齐可选列：

```sql
create table if not exists public.community_papers (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  description text not null default '' check (char_length(description) <= 500),
  file_url text not null,
  file_name text not null,
  file_type text not null default 'pdf',
  file_size bigint,
  nickname text,
  author_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- 若表已存在，只补可选列；必需列按实际情况调整。
alter table public.community_papers add column if not exists description text not null default '';
alter table public.community_papers add column if not exists file_type text not null default 'pdf';
alter table public.community_papers add column if not exists file_size bigint;
alter table public.community_papers add column if not exists nickname text;
alter table public.community_papers add column if not exists created_at timestamptz not null default now();

create index if not exists community_papers_created_at_idx
  on public.community_papers (created_at desc);
```

## 3. 表 RLS

匿名登录用户的 JWT role 也是 `authenticated`，所以策略写 `to authenticated` 即可。

```sql
alter table public.community_papers enable row level security;

drop policy if exists "papers are readable" on public.community_papers;
create policy "papers are readable"
  on public.community_papers
  for select
  to anon, authenticated
  using (true);

drop policy if exists "authenticated can create papers" on public.community_papers;
create policy "authenticated can create papers"
  on public.community_papers
  for insert
  to authenticated
  with check (auth.uid() = author_id);

drop policy if exists "authors can delete papers" on public.community_papers;
create policy "authors can delete papers"
  on public.community_papers
  for delete
  to authenticated
  using (auth.uid() = author_id);
```

如果上传者列叫 `uploader_id`，把上面两处 `author_id` 改成 `uploader_id`。

## 4. Storage Bucket

Bucket 已建时不用重复创建；确认它是 **Public**、限制 10MB、只允许 PDF/PNG/JPEG：

```sql
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'papers',
  'papers',
  true,
  10485760,
  array['application/pdf', 'image/png', 'image/jpeg']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;
```

## 5. Storage 策略

上传路径是 `<userId>/...`，所以用路径第一段限制“只能写自己的目录”：

```sql
drop policy if exists "papers public read" on storage.objects;
create policy "papers public read"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'papers');

drop policy if exists "papers authenticated upload" on storage.objects;
create policy "papers authenticated upload"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'papers'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "papers author delete" on storage.objects;
create policy "papers author delete"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'papers'
    and (storage.foldername(name))[1] = auth.uid()::text
  );
```

## 6. 自测

```sql
-- 应有 1 行
select id, title, file_url, created_at
from public.community_papers
order by created_at desc
limit 1;
```

浏览器上传成功后，`papers` 桶里应出现 `<当前用户 id>/...` 文件；如果插入被 RLS 拒绝，看浏览器 Network 里 `community_papers` 的 401/403 响应，并核对第 3 节策略的列名。
