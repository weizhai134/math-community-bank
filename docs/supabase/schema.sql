-- ---------- 1. 题目表 ----------
create table if not exists public.community_questions (
  id bigint generated by default as identity primary key,
  chapter smallint not null check (chapter between 1 and 7),
  topic text not null check (char_length(topic) between 2 and 30),
  difficulty text not null check (difficulty in ('基础', '进阶', '挑战')),
  type text not null check (type in ('choice', 'judge', 'solution')),
  stem text not null check (char_length(stem) between 5 and 500),
  options jsonb,
  answer jsonb not null,
  explanation text not null check (char_length(explanation) between 5 and 1000),
  source text not null check (source in ('原创', '网络改编')),
  nickname text not null check (char_length(nickname) between 2 and 20),
  author_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'visible', 'hidden')),
  report_count integer not null default 0 check (report_count >= 0),
  content_hash text not null,
  created_at timestamptz not null default now()
);

comment on table public.community_questions is '社区题：先发后审，提交即 visible；举报达阈值由触发器置 hidden。';

create index if not exists community_questions_status_created_idx
  on public.community_questions (status, created_at desc);
create index if not exists community_questions_filter_idx
  on public.community_questions (chapter, difficulty, type);
create index if not exists community_questions_hash_idx
  on public.community_questions (content_hash);
create index if not exists community_questions_author_idx
  on public.community_questions (author_id, created_at desc);

-- ---------- 2. 举报表 ----------
create table if not exists public.community_reports (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.community_questions (id) on delete cascade,
  reporter_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint community_reports_one_per_user unique (question_id, reporter_id)
);

create index if not exists community_reports_question_idx
  on public.community_reports (question_id);

-- ---------- 3. 举报计数 + 阈值隐藏（security definer，绕过 RLS 更新） ----------
create or replace function public.sync_question_reports()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  total integer;
begin
  select count(*) into total
  from public.community_reports
  where question_id = new.question_id;

  update public.community_questions
     set report_count = total,
         status = case when total >= 3 then 'hidden' else status end
   where id = new.question_id;

  return new;
end;
$$;

drop trigger if exists trg_sync_question_reports on public.community_reports;
create trigger trg_sync_question_reports
after insert on public.community_reports
for each row execute function public.sync_question_reports();

-- ---------- 4. 开启 RLS ----------
alter table public.community_questions enable row level security;
alter table public.community_reports enable row level security;

-- ---------- 5. 策略 ----------
drop policy if exists community_questions_select_visible on public.community_questions;
create policy community_questions_select_visible
  on public.community_questions
  for select
  to anon, authenticated
  using (status = 'visible');

drop policy if exists community_questions_insert_own on public.community_questions;
create policy community_questions_insert_own
  on public.community_questions
  for insert
  to authenticated
  with check (auth.uid() = author_id and status = 'visible');

drop policy if exists community_questions_delete_own on public.community_questions;
create policy community_questions_delete_own
  on public.community_questions
  for delete
  to authenticated
  using (auth.uid() = author_id);

-- 不建立 update 策略：普通用户不能改题；举报计数由 security definer 触发器维护。

drop policy if exists community_reports_insert_own on public.community_reports;
create policy community_reports_insert_own
  on public.community_reports
  for insert
  to authenticated
  with check (auth.uid() = reporter_id);

-- 不建立 select 策略：客户端读不到全量举报（只有触发器以 definer 身份统计）。

-- ---------- 6. 权限收敛 ----------
revoke all on public.community_questions from anon, authenticated;
revoke all on public.community_reports from anon, authenticated;

grant select on public.community_questions to anon, authenticated;
grant insert, delete on public.community_questions to authenticated;
grant insert on public.community_reports to authenticated;

grant usage, select on sequence public.community_questions_id_seq to authenticated;
grant usage, select on sequence public.community_reports_id_seq to authenticated;

